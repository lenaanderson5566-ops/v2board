"""Merge explicit node contracts without regenerating unrelated user contracts."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
node = json.loads((root / 'docs/api-v10/node-api.json').read_text(encoding='utf-8'))
target = root / 'docs/api-v10/openapi.json'
document = json.loads(target.read_text(encoding='utf-8'))
document['info']['description'] = 'User API and V2Box machine API. Administrative, operations and legacy node contracts remain available separately. The unfinished staff API is retired.'
document['paths'] = {path: value for path, value in document['paths'].items() if not path.startswith('/nodes/v2box/')}
document['paths'].update(node['paths'])
document['components']['schemas'].update(node['schemas'])
document['components']['securitySchemes']['nodeBearer'] = {'type': 'http', 'scheme': 'bearer', 'description': 'Panel server_token for V2Box machine API. Query tokens are not accepted.'}
document['components']['securitySchemes']['nodeReportBearer'] = {'type':'http','scheme':'bearer','description':'Per-node DDNS report key. Stored hashed; cannot call other machine endpoints.'}

target.write_text(json.dumps(document, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

marker = '\n## V2Box node V10 API\n'
target = root / 'docs/api-v10/mapping.md'
content = target.read_text(encoding='utf-8').split(marker)[0]
content += marker + '\nV2Node and explicitly configured legacy V2Box installations retain their existing routes. These new machine endpoints use a separate bearer credential. See node-api.json for schemas.\n\n| Legacy | V10 |\n|---|---|\n'
for entry in node['endpoints']:
    content += f"| `{entry['legacy']}` | `{entry['method']} /api/v10{entry['path']}` |\n"
target.write_text(content, encoding='utf-8')

def ts(schema):
    if '$ref' in schema: return 'V10' + schema['$ref'].split('/')[-1][0].upper() + schema['$ref'].split('/')[-1][1:]
    kind = schema.get('type')
    if kind == 'object':
        result = 'Record<string, unknown>' if schema.get('additionalProperties') else '{ ' + '; '.join(json.dumps(k) + ('' if k in schema.get('required', []) else '?') + ': ' + ts(v) for k, v in schema.get('properties', {}).items()) + ' }'
    elif kind == 'array': result = 'Array<' + ts(schema['items']) + '>'
    else: result = {'integer':'number','boolean':'boolean','string':'string'}.get(kind, 'unknown')
    return result + (' | null' if schema.get('nullable') else '')

marker = '\n// V2Box machine contracts (generated by document-node-v10.py)\n'
target = root / 'frontend/src/shared/v10-types.ts'
content = target.read_text(encoding='utf-8').split(marker)[0] + marker
for name, schema in node['schemas'].items(): content += 'export type V10' + name[0].upper() + name[1:] + ' = ' + ts(schema) + ';\n'
target.write_text(content, encoding='utf-8')
